# Additive, independent-feature scenario (tag _ADD) with analytically known contributions -> H2 recovery test
# ----------------------------------------------------------------------------------------------------------
def additive_truth_funcs(fo):
    return dict(
        svf=lambda d: 8.0 * d["svf_med"],
        hw=lambda d: -1.5 * np.minimum(d["hw_ratio"], 2.0),
        tcover=lambda d: -5.0 * d["tcover15"],
        ventilation=lambda d: -3.0 * d["ratio_med_b15"],
        orientation=lambda d: 1.2 * np.cos(np.deg2rad(2 * C.axis_angle(d["azimuth_deg"], fo["sun_az"]))),
    )


def generate_additive(seed: int = 11, n: int = 9000):
    rng = np.random.default_rng(seed)
    x0, y0 = 500000.0, 4250000.0
    x, y = x0 + rng.uniform(0, 20000, n), y0 + rng.uniform(0, 20000, n)
    seg = pd.DataFrame(dict(seg_id=np.arange(n), tile_id="T_0500_4250", x_mid=x, y_mid=y,
                            lcz_primary=rng.choice([2, 3, 5, 6, 8, 11, 12], n), district=rng.choice(list("ABCDEFGH"), n),
                            azimuth_deg=rng.uniform(0, 180, n), hw_ratio=rng.uniform(0.1, 3.0, n),
                            bh_mean30=rng.uniform(3, 30, n), bcover30=rng.uniform(0, .6, n), tcover15=rng.uniform(0, .8, n),
                            tht15=rng.uniform(3, 12, n), dist_coast_m=rng.uniform(100, 8000, n),
                            elev_m=rng.uniform(2, 120, n), slope_deg=rng.uniform(0, 12, n), lst_med=33 + rng.normal(size=n),
                            length_m=rng.uniform(30, 200, n), n_ps=rng.integers(25, 300, n), is_synthetic=True))
    seg["lcz_weak250"] = seg["lcz_primary"]
    for L in (50, 100, 250, 500):
        seg[f"g{L:03d}_id"] = [f"{int(a // L)}_{int(b // L)}" for a, b in zip(x, y)]
    out, truth = {}, {}
    for day in C.DAYS:
        fo = C.forcing_summary(day)
        d = seg.assign(svf_med=rng.uniform(0.1, 0.95, n), ratio_med_b15=rng.uniform(0.2, 1.2, n))
        fs = additive_truth_funcs(fo)
        contrib = {k: np.asarray(f(d), float) for k, f in fs.items()}
        m1 = 30.0 + sum(contrib.values()) + rng.normal(0, 0.4, n)
        met = pd.DataFrame({"seg_id": seg["seg_id"], "n_ps_valid": seg["n_ps"], "svf_med": d["svf_med"],
                            "ratio_med_b15": d["ratio_med_b15"], "utci_b15": m1, "utci_unif_b15": m1,
                            "tmrt_b15": m1 + 20, "v10eff_b15": np.clip(fo["u10"] * d["ratio_med_b15"], 0.5, 17),
                            "shade_frac_10_18": rng.uniform(0, 1, n), "m2_strong": rng.integers(0, 9, n),
                            "m2_vstrong": rng.integers(0, 3, n), "partial_run": True, "n_tiles_at_extraction": 1,
                            "is_synthetic": True})
        out[day] = met
        mean_abs = {k: float(np.mean(np.abs(v - v.mean()))) for k, v in contrib.items()}
        tot = sum(mean_abs.values())
        fam = {"shade_geometry": mean_abs["svf"] + mean_abs["hw"], "vegetation": mean_abs["tcover"],
               "ventilation": mean_abs["ventilation"], "orientation": mean_abs["orientation"], "context": 0.0}
        truth[day] = dict(true_family_share={k: v / tot for k, v in fam.items()},
                          true_range_over_q2p5_q97p5={
                              "svf_med": float(8.0 * (np.quantile(d["svf_med"], .975) - np.quantile(d["svf_med"], .025))),
                              "hw_ratio": float(abs(-1.5 * (min(np.quantile(d["hw_ratio"], .975), 2) - np.quantile(d["hw_ratio"], .025)))),
                              "tcover15": float(5.0 * (np.quantile(d["tcover15"], .975) - np.quantile(d["tcover15"], .025)))})
    return seg, out, truth


def write_additive():
    seg, mets, truth = generate_additive()
    base = C.OUT_ROOT / "h1" / "synthetic_inputs"
    base.mkdir(parents=True, exist_ok=True)
    seg_p, met_p = C.default_paths(True, "_ADD")
    seg.to_parquet(seg_p)
    for d, m in mets.items():
        m.to_parquet(met_p[d])
    (base / "truth_SYNTHETIC_ADD.json").write_text(json.dumps(truth, indent=2), encoding="utf-8")
    return truth

"""SYNTHETIC test tables that follow analysis_schema.md section A (rule 6: is_synthetic=True, SYNTHETIC in filename).

These are NOT observations. They are generated by a known data-generating process (planted effects) so the
analysis code can be shown to recover them (or to return NOT SUPPORTED when the planted effect is absent).
Ground truth of every scenario is returned by `truth()` and written next to the tables.

Scenarios (tag):
  _H1T   : LCZ barely matters, street morphology dominates   -> H1 SUPPORTED expected, H4 shade-dominated
  _H1F   : strong LCZ offsets, weak morphology               -> H1 NOT SUPPORTED expected
  _BREEZE: tiny Tmrt spread, large wind-ratio spread         -> H4 NOT shade-dominated expected
Outputs go to outputs/street/analysis/h1/synthetic_inputs/ (the only place this WP may write inputs).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402

BUILT = [2, 3, 5, 6, 8, 9]
NAT = [11, 12, 14]
RARE = 10      # deliberately < 30 segments -> pooling test


def smooth_field(x, y, rng, k=6, scale=6000.0):
    f = np.zeros_like(x, float)
    for _ in range(k):
        kx, ky = rng.normal(0, 1 / scale, 2)
        ph = rng.uniform(0, 2 * np.pi)
        f += np.cos(2 * np.pi * (kx * x + ky * y) + ph)
    return f / np.sqrt(k / 2)


def generate(scenario: str, seed: int = 7, n_tiles_side: int = 20):
    rng = np.random.default_rng(seed)
    x0, y0 = 500000.0, 4250000.0
    rows = []
    sid = 0
    # tile LCZ by 4x4 tile patches
    patch = {}
    for pi in range(n_tiles_side // 4):
        for pj in range(n_tiles_side // 4):
            patch[(pi, pj)] = int(rng.choice(BUILT + NAT, p=[.12, .16, .08, .2, .1, .14, .06, .08, .06]))
    for ti in range(n_tiles_side):
        for tj in range(n_tiles_side):
            tile_lcz = patch[(ti // 4, tj // 4)]
            n = int(rng.integers(22, 42))
            for _ in range(n):
                x = x0 + ti * 1000 + rng.uniform(0, 1000)
                y = y0 + tj * 1000 + rng.uniform(0, 1000)
                lcz = tile_lcz if rng.random() < 0.75 else int(rng.choice(BUILT + NAT))
                rows.append((sid, f"T_{int(x0 // 1000) + ti:04d}_{int(y0 // 1000) + tj:04d}", x, y, lcz))
                sid += 1
    df = pd.DataFrame(rows, columns=["seg_id", "tile_id", "x_mid", "y_mid", "lcz_primary"])
    n = len(df)
    # a handful of rare-class segments to exercise pooling
    idx = rng.choice(n, 12, replace=False)
    df.loc[idx, "lcz_primary"] = RARE
    xr, yr = df["x_mid"].to_numpy() - x0, df["y_mid"].to_numpy() - y0
    # districts: 4 x 2 rectangles over the 20 km square
    di = np.minimum((xr // 5000).astype(int), 3)
    dj = np.minimum((yr // 10000).astype(int), 1)
    df["district"] = [f"D{a}{b}" for a, b in zip(di, dj)]
    # morphology: LCZ-dependent mean but wide within-LCZ spread
    built = df["lcz_primary"].isin(BUILT + [RARE]).to_numpy()
    lcz = df["lcz_primary"].to_numpy()
    spread = 1.0
    sep = 1.0 if scenario == "_H1F" else 0.25    # how strongly LCZ class separates the morphology

    def mix(b, nat):
        mid = 0.5 * (b + nat)
        return np.where(built, mid + sep * (b - mid), mid + sep * (nat - mid))
    base_svf = mix(0.45, 0.85) + 0.02 * ((lcz % 7) - 3) * built
    sf = smooth_field(xr, yr, rng)
    svf = np.clip(base_svf + 0.22 * rng.normal(size=n) * spread + 0.05 * sf, 0.05, 0.99)
    hw = np.clip(mix(1.1, 0.15) * (1.1 - svf) / 0.55 + 0.25 * rng.normal(size=n), 0.02, 4.0)
    bh = np.clip(mix(14, 4) * (1 + 0.5 * rng.normal(size=n)), 2, 60)
    bcov = np.clip(mix(0.38, 0.05) + 0.12 * rng.normal(size=n), 0, 0.9)
    tcov = np.clip(mix(0.12, 0.5) + 0.15 * rng.normal(size=n) + 0.03 * sf, 0, 0.95)
    tht = np.where(tcov > 0.02, np.clip(6 + 2.5 * rng.normal(size=n), 2, 18), np.nan)
    az = rng.uniform(0, 180, n)
    dcoast = np.abs(xr - 2000) + 400 + 300 * rng.random(n)
    elev = 5 + 0.004 * yr + 12 * np.abs(sf) + 3 * rng.random(n)
    slope = np.clip(1 + 2.5 * np.abs(sf) + rng.exponential(1.0, n), 0, 25)
    lst = 33 + 4 * (svf - .5) * -1 + 1.5 * rng.normal(size=n)
    df = df.assign(azimuth_deg=az, hw_ratio=hw, bh_mean30=bh, bcover30=bcov, tcover15=tcov, tht15=tht,
                   dist_coast_m=dcoast, elev_m=elev, slope_deg=slope, lst_med=lst,
                   length_m=rng.uniform(30, 200, n), n_ps=rng.integers(25, 400, n))
    df["lcz_weak250"] = np.where(rng.random(n) < 0.7, df["lcz_primary"], rng.choice(BUILT + NAT, n))
    for L in (50, 100, 250, 500):
        df[f"g{L:03d}_id"] = [f"{int(x // L)}_{int(y // L)}" for x, y in zip(df["x_mid"], df["y_mid"])]
    # ~3 % of segments get LCZ 0 (raster no-data, amendment A6) AFTER the physics below uses the true class
    zero_idx = np.random.default_rng(seed + 99).choice(n, int(0.03 * n), replace=False)
    df["is_synthetic"] = True

    # ---- planted physical chain per day --------------------------------------------------------------
    out = {}
    truth = dict(scenario=scenario, seed=seed, n=n)
    lcz_off = {c: 0.0 for c in BUILT + NAT + [RARE]}
    if scenario == "_H1F":
        for c in lcz_off:
            lcz_off[c] = 4.5 if c in (2, 3, 5) else (2.0 if c in (6, 8, 9, RARE) else -3.0)
        truth["lcz_offset_C"] = lcz_off
    dist_off = {d: v for d, v in zip(sorted(df["district"].unique()), np.linspace(-0.4, 0.4, 8))}
    for day, (ta, rh, u10, tmrt_hi) in {"IMBAT": (34.67, 22.7, 9.6, 30.0), "CALM": (33.0, 40.0, 2.0, 27.0)}.items():
        fo = C.forcing_summary(day)
        ta, rh, u10 = fo["ta"], fo["rh"], fo["u10"]
        ang_sun = C.axis_angle(az, fo["sun_az"])
        ang_wind = C.axis_angle(az, fo["wd_mean_15_17"])
        # sunlit fraction at 15:00: sky openness, trees shade, canyons aligned with sun are sunlit
        sunlit = np.clip(0.1 + 0.95 * svf - 0.55 * tcov + 0.12 * np.cos(np.deg2rad(2 * ang_sun)) * (hw > .8) + 0.08 * rng.normal(size=n), 0, 1)
        if scenario == "_BREEZE":
            tmrt = ta + 3.0 + 1.0 * sunlit + 0.3 * rng.normal(size=n)       # almost no radiative spread
            ratio = np.clip(0.9 + 0.45 * rng.normal(size=n) - 0.2 * hw + 0.3 * np.cos(np.deg2rad(2 * ang_wind)), 0.12, 1.6)
        else:
            tmrt = ta + 4.0 + (tmrt_hi) * sunlit + 1.0 * rng.normal(size=n)
            ratio = np.clip(0.65 - 0.12 * hw + 0.18 * np.cos(np.deg2rad(2 * ang_wind)) + 0.07 * rng.normal(size=n), 0.2, 1.3)
        v = np.clip(u10 * ratio, 0.5, 17.0)
        u = C.utci_vec(ta, tmrt, v, rh)
        off = np.array([lcz_off[c] for c in lcz]) + np.array([dist_off[d] for d in df["district"]])
        utci15 = u + off + 0.15 * rng.normal(size=n)
        uuni = C.utci_vec(ta, tmrt, np.full(n, np.clip(u10, .5, 17)), rh) + off
        met = pd.DataFrame({"seg_id": df["seg_id"].to_numpy(), "n_ps_valid": df["n_ps"].to_numpy()})
        diurnal = {6: -8, 7: -7, 8: -5.5, 9: -4, 10: -2.5, 11: -1.2, 12: -0.5, 13: -.1, 14: 0.0, 15: 0.0, 16: -.3,
                   17: -1.2, 18: -2.7, 19: -4.5, 20: -6.5, 21: -8}
        for b in range(6, 22):
            met[f"utci_b{b:02d}"] = utci15 + diurnal[b] + (0.1 * rng.normal(size=n) if b != 15 else 0)
        met["utci_unif_b15"] = uuni
        met["tmrt_b15"] = tmrt
        met["tmrt_b15_p90"] = tmrt + 3
        met["v10eff_b15"] = v
        met["ratio_med_b15"] = ratio
        met["svf_med"] = np.clip(svf + 0.02 * rng.normal(size=n), 0, 1)
        met["shade_frac_10_18"] = 1 - np.clip(sunlit + 0.05, 0, 1)
        bands = [f"utci_b{b:02d}" for b in C.BANDS_M2]
        met["m2_strong"] = (met[bands] >= C.UTCI_STRONG).sum(axis=1)
        met["m2_vstrong"] = (met[bands] >= C.UTCI_VSTRONG).sum(axis=1)
        met["partial_run"] = True
        met["n_tiles_at_extraction"] = int(df["tile_id"].nunique())
        met["is_synthetic"] = True
        out[day] = met
        truth[day] = dict(ta=ta, rh=rh, u10=u10, sd_tmrt=float(np.std(tmrt)), sd_v=float(np.std(v)),
                          var_utci_planted_offsets=float(np.var(off)),
                          true_lcz_effect_var_share=float(np.var(np.array([lcz_off[c] for c in lcz])) / np.var(utci15)))
    df.loc[zero_idx, ["lcz_primary", "lcz_weak250"]] = 0
    truth["n_lcz0"] = int(len(zero_idx))
    return df, out, truth


def write(scenario: str, seed: int = 7) -> dict:
    df, mets, truth = generate(scenario, seed)
    base = C.OUT_ROOT / "h1" / "synthetic_inputs"
    base.mkdir(parents=True, exist_ok=True)
    seg_p, met_p = C.default_paths(True, scenario)
    df.to_parquet(seg_p)
    for d, m in mets.items():
        m.to_parquet(met_p[d])
    (base / f"truth_SYNTHETIC{scenario}.json").write_text(json.dumps(truth, indent=2, default=str), encoding="utf-8")
    return truth


